LabwareSeedEntry = Annotated[
    Union[
        PlateSeedEntry,
        TipRackSeedEntry,
        TroughSeedEntry,
        TubeSeedEntry,
        CarrierSeedEntry,
    ],
    Field(discriminator="category"),
]


_SEED_LIST_ADAPTER: TypeAdapter[list[LabwareSeedEntry]] = TypeAdapter(list[LabwareSeedEntry])


def load_labware_seed() -> list[LabwareSeedEntry]:
    """Load the labware seed catalog bundled with the cheshire-drivers wheel."""
    seed_path = files("cheshire_drivers").joinpath("labware_seed.json")
    return _SEED_LIST_ADAPTER.validate_json(seed_path.read_text(encoding="utf-8"))


@lru_cache(maxsize=1)
def _carrier_index() -> dict[str, CarrierSeedEntry]:
    return {
        entry.labware_type: entry
        for entry in load_labware_seed()
        if isinstance(entry, CarrierSeedEntry)
    }


def get_carrier_site_identifiers(catalog_ref: str) -> list[str]:
    """Site identifiers for the carrier matching catalog_ref; raises KeyError if unknown or not a carrier."""
    index = _carrier_index()
    if catalog_ref not in index:
        raise KeyError(f"Unknown carrier catalog_ref: {catalog_ref!r}")
    return [site.identifier for site in index[catalog_ref].sites]
