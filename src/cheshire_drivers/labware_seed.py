"""Labware seed catalog: PLR-derived geometry shipped in the cheshire-drivers wheel.

`labware_seed.json` is generated by `scripts/regen_labware_seed.py` from
PyLabRobot's public resource catalog. A hosted deployment's labware-definition
store seeds itself from `load_labware_seed()` at boot.

The discriminated union shape keeps per-category constraints local while
letting consumers iterate a single `list[LabwareSeedEntry]` collection.
Plate entries satisfy the `_HasPlateGeometry` and `_HasWellGeometry`
protocols from `cheshire_drivers.plr.labware_converter`, so
`PLRLabwareConverter.to_plr_plate()` reconstructs a usable PLR `Plate`
directly from a `PlateSeedEntry`.
"""

from functools import lru_cache
from importlib.resources import files
from typing import Annotated, Literal, Union

from pydantic import BaseModel, ConfigDict, Field, TypeAdapter


class WellSeedEntry(BaseModel):
    """Per-well geometry. Satisfies `_HasWellGeometry`."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    identifier: str
    row: int
    col: int
    position_x: float
    position_y: float
    position_z: float
    size_x: float
    size_y: float
    size_z: float
    max_volume: float
    bottom_type: str
    volume: float = 0.0


class PlateSeedEntry(BaseModel):
    """Plate geometry. Satisfies `_HasPlateGeometry`."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    category: Literal["plate"] = "plate"
    labware_type: str
    display_name: str
    vendor: str | None = None
    plr_class_name: str | None = None
    num_rows: int
    num_cols: int
    size_x: float
    size_y: float
    size_z: float
    wells: list[WellSeedEntry]

    @property
    def name(self) -> str:
        return self.labware_type

    def well(self, identifier: str) -> WellSeedEntry:
        for w in self.wells:
            if w.identifier == identifier:
                return w
        raise KeyError(f"well {identifier!r} not in plate {self.labware_type!r}")


